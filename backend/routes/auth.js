const router = require('express').Router();
const auth = require('../middleware/auth');
const optionalAuth = require('../middleware/optionalAuth');
const authorize = require('../middleware/authorize');
const { register, login, googleLogin, googleRegister, updateProfile, resendVerification, verifyEmail, forgotPassword, resetPassword, me, session, refresh, logout, listSessions, revokeOtherSessions, revokeSession, adminCheck, referrals } = require('../controllers/authController');
router.post('/register', register);
router.post('/login', login);
router.post('/google', googleLogin);
router.post('/google/register', googleRegister);
router.post('/verify-email', verifyEmail);
router.post('/resend-verification', resendVerification);
router.post('/password/forgot', forgotPassword);
router.post('/password/reset', resetPassword);
router.patch('/profile', auth, updateProfile);
router.post('/refresh', refresh);
router.post('/logout', logout);
router.get('/session', optionalAuth, session);
router.get('/me', auth, me);
router.get('/referrals', auth, referrals);
router.get('/sessions', auth, listSessions);
router.delete('/sessions/others', auth, revokeOtherSessions);
router.delete('/sessions/:sessionId', auth, revokeSession);
router.get('/admin-check', auth, authorize('admin'), adminCheck);
module.exports = router;
